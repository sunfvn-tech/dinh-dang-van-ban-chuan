# Sinh bảng độ rộng ký tự Times New Roman (Liberation Serif tương thích số đo)
from fontTools.ttLib import TTFont
import sys
def table(path):
    f=TTFont(path); cmap=f.getBestCmap(); hm=f['hmtx']; upm=f['head'].unitsPerEm
    rng=list(range(0x20,0x7f))+list(range(0xa0,0x250))+list(range(0x1ea0,0x1efa))+list(range(0x2010,0x2027))
    out={}
    for c in rng:
        if c in cmap: out[c]=hm[cmap[c]][0]
    return upm,out
u,r=table('/usr/share/fonts/truetype/liberation/LiberationSerif-Regular.ttf')
_,b=table('/usr/share/fonts/truetype/liberation/LiberationSerif-Bold.ttf')
w=open(sys.argv[1],'w')
w.write('// Code generated by tools/gen_widths.py. DO NOT EDIT.\n\npackage core\n\nconst fontUPM = %d\n\n'%u)
for name,t in (('widthRegular',r),('widthBold',b)):
    w.write('var %s = map[rune]uint16{'%name)
    w.write(','.join('%d:%d'%(k,v) for k,v in sorted(t.items())))
    w.write('}\n\n')
